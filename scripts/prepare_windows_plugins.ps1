[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) {
    throw 'This opt-in plugin junction helper runs on Windows only.'
}
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..')).TrimEnd('\')

function Get-ExistingItem([string]$Path) {
    try { return Get-Item -LiteralPath $Path -Force -ErrorAction Stop }
    catch {
        if ($_.CategoryInfo.Category -eq 'ObjectNotFound') { return $null }
        throw
    }
}

function Test-Within([string]$Path, [string]$Parent) {
    return $Path.Equals($Parent, [StringComparison]::OrdinalIgnoreCase) -or
        $Path.StartsWith($Parent.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)
}

function Assert-PlainParents([string]$Path) {
    $full = [IO.Path]::GetFullPath($Path).TrimEnd('\')
    if (-not (Test-Within $full $root)) { throw "Plugin parent escapes this checkout: $Path" }
    $current = $root
    $components = @('') + @($full.Substring($root.Length).TrimStart('\').Split('\') | Where-Object { $_ })
    foreach ($component in $components) {
        if ($component) { $current = Join-Path $current $component }
        $item = Get-ExistingItem $current
        if ($null -ne $item -and (-not $item.PSIsContainer -or
            ($item.Attributes -band [IO.FileAttributes]::ReparsePoint))) {
            throw "Plugin parent must be an ordinary checkout directory: $current"
        }
    }
}

function Read-JsonObject([string]$Path) {
    $text = Get-Content -LiteralPath $Path -Raw -Encoding UTF8
    if (-not $text.TrimStart().StartsWith('{')) { throw "Expected a JSON object: $Path" }
    $value = $text | ConvertFrom-Json
    if (-not (Test-JsonObject $value)) { throw "Expected a JSON object: $Path" }
    return $value
}

function Test-JsonObject($Value) {
    return $null -ne $Value -and $Value.GetType().FullName -eq 'System.Management.Automation.PSCustomObject'
}

function Required-Property($Object, [string]$Name) {
    if (-not (Test-JsonObject $Object) -or $null -eq $Object.PSObject.Properties[$Name]) {
        throw "Plugin metadata is missing a valid '$Name' property."
    }
    return ,$Object.PSObject.Properties[$Name].Value
}

function Test-PluginLink($Entry) {
    $item = Get-ExistingItem $Entry.destination
    if ($null -eq $item) { return $false }
    if (-not $item.PSIsContainer -or -not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -or
        $item.LinkType -notin @('Junction', 'SymbolicLink')) {
        throw "Conflicting plugin entry; nothing will be replaced: $($Entry.destination)"
    }
    $targets = @($item.Target)
    if ($targets.Count -ne 1 -or $targets[0] -isnot [string] -or -not $targets[0]) {
        throw "Cannot verify plugin link target: $($Entry.destination)"
    }
    $target = $targets[0]
    if (-not [IO.Path]::IsPathRooted($target)) {
        $target = Join-Path ([IO.Path]::GetDirectoryName($Entry.destination)) $target
    }
    $target = [IO.Path]::GetFullPath($target).TrimEnd('\')
    if (-not $target.Equals($Entry.target, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Stale plugin link target; review it manually: $($Entry.destination)"
    }
    return $true
}

Assert-PlainParents (Join-Path $root 'upstream')
$metadataPath = Join-Path $root 'upstream\.flutter-plugins-dependencies'
if (-not (Test-Path -LiteralPath $metadataPath -PathType Leaf)) {
    throw 'Plugin metadata is missing. Run the pinned Flutter pub get first, then rerun this helper if plugin symlink creation fails.'
}
$metadata = Read-JsonObject $metadataPath
$pin = Read-JsonObject (Join-Path $root 'scripts\toolchain.json')
$version = Required-Property $metadata 'version'
$expectedVersion = Required-Property $pin 'flutter_version'
if ($version -isnot [string] -or $expectedVersion -isnot [string] -or $version -ne $expectedVersion) {
    throw 'Plugin metadata was generated by a different Flutter version. Refresh it with the pinned SDK.'
}
$plugins = Required-Property $metadata 'plugins'
if (-not (Test-JsonObject $plugins)) { throw 'Plugin metadata plugins must be an object.' }
$parents = @('windows', 'linux') | ForEach-Object {
    Join-Path $root "upstream\$_\flutter\ephemeral\.plugin_symlinks"
}
$plan = [Collections.Generic.List[object]]::new()
foreach ($platform in @('windows', 'linux')) {
    $platformRoot = Join-Path $root "upstream\$platform\flutter"
    Assert-PlainParents $platformRoot
    if (-not (Test-Path -LiteralPath $platformRoot -PathType Container)) {
        throw "Checkout platform directory is missing: $platformRoot"
    }
    $parent = Join-Path $platformRoot 'ephemeral\.plugin_symlinks'
    Assert-PlainParents $parent
    $property = $plugins.PSObject.Properties[$platform]
    $entries = @()
    if ($null -ne $property) {
        if ($property.Value -isnot [array]) { throw "Plugin metadata '$platform' must be an array." }
        $entries = $property.Value
    }
    $names = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($plugin in $entries) {
        $name = Required-Property $plugin 'name'
        $path = Required-Property $plugin 'path'
        if ($name -isnot [string] -or $name.Length -gt 255 -or $name -cnotmatch '^[a-z_][a-z0-9_]*$' -or
            $name -match '^(con|prn|aux|nul|com[1-9]|lpt[1-9])$' -or -not $names.Add($name)) {
            throw "Invalid or duplicate $platform plugin name: $name"
        }
        if ($path -isnot [string] -or $path -notmatch '^[A-Za-z]:[\\/]' -or $path.IndexOf([char]0) -ge 0) {
            throw "Plugin target must be an absolute local directory: $name"
        }
        $target = [IO.Path]::GetFullPath($path).TrimEnd('\')
        if ($target -match '^[A-Za-z]:$') { throw "Plugin target must be below a volume root: $name" }
        $targetItem = Get-ExistingItem $target
        if ($null -eq $targetItem -or -not $targetItem.PSIsContainer -or
            ($targetItem.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
            throw "Plugin target is missing or is not an ordinary directory: $target"
        }
        foreach ($outputParent in $parents) {
            if ((Test-Within $target $outputParent) -or (Test-Within $outputParent $target)) {
                throw "Plugin target overlaps generated plugin paths: $target"
            }
        }
        $entry = [pscustomobject]@{ name = $name; parent = $parent; target = $target; destination = (Join-Path $parent $name) }
        [void](Test-PluginLink $entry)
        $plan.Add($entry)
    }
    if (Test-Path -LiteralPath $parent -PathType Container) {
        foreach ($child in Get-ChildItem -LiteralPath $parent -Force) {
            if (-not $names.Contains($child.Name)) { throw "Unexpected stale plugin entry; review it manually: $($child.FullName)" }
        }
    }
}

# No directories or links are created until every platform entry is validated.
$created = [Collections.Generic.List[string]]::new()
$retained = [Collections.Generic.List[string]]::new()
foreach ($entry in $plan) {
    Assert-PlainParents $entry.parent
    if (Test-PluginLink $entry) { $retained.Add($entry.destination); continue }
    [void][IO.Directory]::CreateDirectory($entry.parent)
    Assert-PlainParents $entry.parent
    Push-Location -LiteralPath $entry.parent
    try {
        # Validated names are plain identifiers; target values remain data.
        New-Item -ItemType Junction -Name $entry.name -Value ([WildcardPattern]::Escape($entry.target)) | Out-Null
    } finally { Pop-Location }
    if (-not (Test-PluginLink $entry)) { throw "Could not verify created plugin junction: $($entry.destination)" }
    $created.Add($entry.destination)
}
[ordered]@{ root = $root; metadata = $metadataPath; created = @($created.ToArray()); retained = @($retained.ToArray()) } |
    ConvertTo-Json -Depth 4
