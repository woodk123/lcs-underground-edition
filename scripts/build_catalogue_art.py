"""Regenerate supplemental Dart crop mappings from inspected art provenance.

PNG masters stay unchanged. --encode regenerates only supplemental runtime art;
the exporter refreshes catalogue hashes, static records and the Dart crop map.
"""
from pathlib import Path
import json
import argparse

from release_common import digest, write_json


def build(root: Path, encode: bool = False) -> None:
    path = root / 'assets/catalogue/provenance.json'
    provenance = json.loads(path.read_text(encoding='utf-8'))
    manifest_path = root / 'assets/runtime-art/manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    records = {a['runtime_path']: a for a in manifest['assets']}
    lines = ["// Generated by scripts/build_catalogue_art.py; edit provenance instead.",
             "part of 'catalogue_art.dart';", '',
             'const _supplementalEquipment = <String, CatalogueArtEntry>{']
    for asset in provenance['assets']:
        if asset.get('supplemental'):
            source, runtime = root / asset['source_path'], root / asset['runtime_path']
            if encode:
                from PIL import Image
                from runtime_images import save_runtime_image
                with Image.open(source) as image:
                    save_runtime_image(image, runtime)
            records[asset['runtime_path']] = {
                'original_path': asset['source_path'], 'runtime_path': asset['runtime_path'],
                'width': asset['width'], 'height': asset['height'], 'mode': 'RGBA',
                'lossless': False, 'has_alpha': True,
                'original_sha256': digest(source), 'runtime_sha256': digest(runtime),
                'original_bytes': source.stat().st_size, 'runtime_bytes': runtime.stat().st_size,
            }
        asset['source_sha256'] = digest(root / asset['source_path'])
        asset['runtime_sha256'] = digest(root / asset['runtime_path'])
        if not asset.get('supplemental'):
            continue
        runtime = asset['runtime_path'].removeprefix('upstream/')
        for entry in asset['entries']:
            rect = ', '.join(str(v) for v in entry['source_rect'])
            lines.extend([f"  '{entry['type_id']}': CatalogueArtEntry(",
                          f"    '{runtime}',", f'    Rect.fromLTWH({rect}),', '  ),'])
    lines.append('};')
    (root / 'upstream/lib/modern/catalogue_art_supplement.dart').write_text(
        '\n'.join(lines) + '\n', encoding='utf-8')
    write_json(path, provenance)
    manifest['assets'] = list(records.values())
    write_json(manifest_path, manifest)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--encode', action='store_true')
    build(Path(__file__).resolve().parents[1], parser.parse_args().encode)
