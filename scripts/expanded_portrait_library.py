"""Package the append-only 1,024 portrait expansion after independent source QA.

Partial mode writes review evidence only. Publishing requires every source hash
to have an explicit passed review; it never rewrites the original 378 slots.
"""
import argparse
from collections import Counter
import json
from pathlib import Path

from PIL import Image
from portrait_library import ROOT, digest, write_json
from runtime_images import RUNTIME_ENCODING, save_runtime_image


def casting_hash(spec):
    """Bind source review to saved IDs, role and authored age rows as well."""
    fields={name:spec[name] for name in ('batch','firstId','group','rowAges')}
    return digest(json.dumps(fields,sort_keys=True,separators=(',',':')).encode('utf-8'))


def build(partial=False, approvals=None, runtime_review=False):
    library = ROOT / 'assets/portraits-v4'
    target = ROOT / 'upstream/assets/modern/portraits_v2'
    review = ROOT / '.local/art-review/portraits-v4'
    brief = json.loads((library / 'prompts.json').read_text(encoding='utf-8'))
    overrides = json.loads((library / 'prompt-overrides.json').read_text(encoding='utf-8'))
    geometry = json.loads((library / 'crop-overrides.json').read_text(encoding='utf-8'))
    if approvals:
        passed = json.loads(approvals.read_text(encoding='utf-8'))
    elif (library/'manifest.json').is_file():
        # Already-reviewed masters can be re-encoded from a clean checkout.
        approved = json.loads((library/'manifest.json').read_text(encoding='utf-8'))
        passed = {str(a['batch']):dict(a,status=a.get('sourceReview')) for a in approved['atlases']}
    else:
        passed = {}
    entries, atlases, prepared, missing, unapproved = [], [], [], [], []
    seen = set()
    for version in ('v2', 'v3'):
        previous = json.loads((ROOT / f'assets/portraits-{version}/manifest.json').read_text())
        seen.update(p['cropSha256'] for p in previous['portraits'])
    dart = ["// Generated by scripts/expanded_portrait_library.py; preserve saved IDs.", "part of 'portrait.dart';", '', 'const expandedPortraitEntries = <PortraitEntry>[']
    for spec in brief['batches']:
        batch = spec['batch']
        path = library / f'source/batch_{batch:02}.png'
        if not path.is_file():
            missing.append(path.name)
            continue
        source_hash = digest(path.read_bytes())
        approval = passed.get(str(batch), {})
        with Image.open(path) as original:
            original.load()
            if original.format != 'PNG' or original.width != original.height or original.width < 1024:
                raise ValueError(f'{path.name}: expected square PNG >=1024px')
            image = original.convert('RGB')
        edges = [round(n * image.width / 4) for n in range(5)]
        mapping = geometry.get(str(batch), {})
        columns = mapping.get('columnEdges', edges)
        rows = mapping.get('rowEdges', edges)
        for axis in (columns, rows):
            if (len(axis) != 5 or axis[0] != 0 or axis[-1] != image.width
                    or any(type(n) is not int for n in axis)
                    or any(a >= b for a, b in zip(axis, axis[1:]))):
                raise ValueError(f'{path.name}: invalid source crop boundaries')
        accepted = (approval.get('status') == 'passed'
                    and approval.get('sourceSha256') == source_hash
                    and approval.get('castingSha256') == casting_hash(spec)
                    and approval.get('columnEdges') == columns
                    and approval.get('rowEdges') == rows)
        if not accepted:
            unapproved.append(batch)
        runtime = Image.new('RGB', (1024, 1024))
        for cell in range(16):
            row, col = divmod(cell, 4)
            box = (columns[col], rows[row], columns[col+1], rows[row+1])
            crop = image.crop(box)
            crop_hash = digest(crop.tobytes())
            if crop_hash in seen:
                raise ValueError(f'Duplicate portrait crop in batch{batch} cell{cell}')
            seen.add(crop_hash)
            runtime.paste(crop.resize((256,256),Image.Resampling.LANCZOS),(col*256,row*256))
            identity = spec['firstId'] + cell
            gender = 'female' if col%2 == 0 else 'male'
            if spec['group']=='canine': gender='nonbinary'
            entry = {'id':f'portrait_{identity:03}', 'index':identity, 'batch':batch,
                     'asset':f'assets/modern/portraits_v2/batch_{batch:02}.webp',
                     'row':row, 'column':col, 'professionGroup':spec['group'],
                     'presentation':'unspecified' if spec['group']=='canine' else gender,
                     'visualAge':spec['rowAges'][row],
                     'rect':[col*256,row*256,256,256],
                     'sourceRect':[box[0],box[1],box[2]-box[0],box[3]-box[1]],
                     'cropSha256':crop_hash}
            entries.append(entry)
            dart.append(f"  PortraitEntry({identity}, PortraitBackground.{spec['group']}, Gender.{gender}, {entry['visualAge']}),")
        prompt = overrides.get(str(batch),spec['prompt'])
        atlases.append({'batch':batch,'source':f'source/{path.name}',
                       'asset':f'assets/modern/portraits_v2/batch_{batch:02}.webp',
                       'sourceSize':list(image.size),'runtimeSize':[1024,1024],
                       'validPortraits':16,'sourceSha256':source_hash,
                       'columnEdges':columns,'rowEdges':rows,
                       'castingSha256':casting_hash(spec),
                       'promptSha256':digest(prompt.encode('utf-8')),
                       'sourceReview': 'passed' if accepted else 'pending'})
        prepared.append((batch,runtime))
    dart.append('];')
    metadata={'version':4,'portraitCount':len(entries),'firstId':378,'lastId':1401,
              'basePortraitCount':378,'combinedPortraitCount':378+len(entries),
              'gridColumns':4,'gridRows':4,'runtimeAtlasSize':1024,
              'runtimeEncoding':RUNTIME_ENCODING,'complete':not missing,
              'missingAtlases':missing,'unapprovedBatches':unapproved,
              'counts':dict(Counter(e['professionGroup'] for e in entries)),
              'atlases':atlases,'portraits':entries}
    if partial:
        if runtime_review:
            for batch,runtime in prepared:
                save_runtime_image(runtime,review/f'runtime/batch_{batch:02}.webp')
        write_json(review/'validation-partial.json',metadata)
    else:
        if missing or unapproved or len(entries)!=1024:
            raise ValueError(f'Publish blocked: missing={missing}; unapproved={unapproved}; count={len(entries)}')
        if [e['index'] for e in entries] != list(range(378,1402)):
            raise ValueError('Expansion IDs must be contiguous 378–1401')
        for batch,runtime in prepared:
            save_runtime_image(runtime,target/f'batch_{batch:02}.webp')
        for atlas in atlases:
            atlas['runtimeSha256']=digest((ROOT/'upstream'/atlas['asset']).read_bytes())
        write_json(library/'manifest.json',metadata)
        write_json(target/'manifest-v4.json',metadata)
        (ROOT/'upstream/lib/creature/portrait_expansion.dart').write_text('\n'.join(dart)+'\n',encoding='utf-8')
    return {'portraits':len(entries),'missing':len(missing),'unapproved':unapproved,'published':not partial}


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--partial',action='store_true')
    parser.add_argument('--approvals',type=Path)
    parser.add_argument('--runtime-review',action='store_true',help='Encode ignored runtime previews in partial mode')
    args=parser.parse_args()
    if args.runtime_review and not args.partial:
        parser.error('--runtime-review requires --partial')
    print(json.dumps(build(args.partial,args.approvals,args.runtime_review),indent=2))
