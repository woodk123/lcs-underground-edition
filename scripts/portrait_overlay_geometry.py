"""Export packed painted-overlay content rectangles for the runtime painter."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root/'upstream/assets/modern/portraits_v2/manifest-v3.json').read_text())['appearanceOverlays']
w,h = manifest['runtimeSize']
lines = []
for overlay in manifest['overlays']:
    x,y,cw,ch = overlay['contentRect']
    lines.append(f"  Rect.fromLTWH({x/w:.8f}, {y/h:.8f}, {cw/w:.8f}, {ch/h:.8f}), // {overlay['name']}")
(root/'upstream/lib/modern/portrait_overlay_geometry.dart').write_text("// Generated by scripts/portrait_overlay_geometry.py from manifest-v3.json.\nimport 'dart:ui';\n\nconst portraitOverlayContentRects = <Rect>[\n"+'\n'.join(lines)+'\n];\n')
