"""Build a read-only catalogue of possible site features and loose loot."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'upstream'
source = (ROOT / 'lib/sitemode/sitemap.dart').read_text()
templates = {}
for match in re.finditer(r'(SiteType\.\w+(?:\s*\|\|\s*SiteType\.\w+)*)\s*=>\s*"([^"]+)"', source):
    for site in re.findall(r'SiteType\.(\w+)', match[1]):
        templates.setdefault(site, []).append(match[2])

maps = {}
current = None
for raw in (ROOT / 'assets/maps/sitemaps.txt').read_text().splitlines():
    if raw.lstrip().startswith('#'):
        continue
    parts = raw.split()
    if len(parts) < 2:
        continue
    command, value = parts[:2]
    if command == 'OBJECT':
        current = {'parent': None, 'features': []}
    elif current is not None:
        if command == 'NAME': maps[value] = current
        elif command == 'USE': current['parent'] = value
        elif command in ('SPECIAL', 'UNIQUE'): current['features'].append(value)

lookup = dict(re.findall(r'"([A-Z_]+)"\s*=>\s*TileSpecial\.(\w+)', (ROOT / 'lib/sitemode/sitemap_from_tabscript.dart').read_text()))
csv_ids = dict((int(i), name) for i, name in re.findall(r'(\d+): TileSpecial\.(\w+)', (ROOT / 'lib/sitemode/sitemap_from_dame.dart').read_text()))

def features(name, seen=None):
    seen = set() if seen is None else seen
    if name in seen: return []
    seen.add(name)
    template = maps.get(name)
    if not template: return []
    return features(template['parent'], seen) + [lookup[x] for x in template['features'] if x in lookup]

feature_rows = []
for site, names in sorted(templates.items()):
    found = set()
    for name in names:
        found.update(features(name))
        for path in (ROOT / 'assets/maps').glob(f'mapCSV_{name}*_Specials.csv'):
            for token in re.findall(r'-?\d+', path.read_text()):
                if int(token) in csv_ids: found.add(csv_ids[int(token)])
    found -= {'none', 'stairsUp', 'stairsDown', 'signOne', 'signTwo', 'signThree'}
    if found:
        feature_rows.append(f'  SiteType.{site}: [{", ".join("TileSpecial." + x for x in sorted(found))}],')

loot_source = (ROOT / 'lib/sitemode/map_specials.dart').read_text().split('Item? lootItemForSite(SiteType site) {')[1]
loot_rows = []
pending = []
for match in re.finditer(r'((?:\s*case SiteType\.\w+:)+)(.*?)(?=\s*case SiteType\.|\s*default:)', loot_source, re.S):
    ids = re.findall(r'LootTypeIds\.\w+|"(?:WEAPON|CLOTHING)_[A-Z0-9_]+"', match[2])
    ids = list(dict.fromkeys(ids))
    for site in re.findall(r'SiteType\.(\w+)', match[1]):
        if ids: loot_rows.append(f'  SiteType.{site}: [{", ".join(ids)}],')

output = '''// Generated by scripts/generate_location_catalog.py from map and loot data.
// These are possible contents across templates, never a live floor inventory.
import 'package:lcs_new_age/items/loot_type.dart';
import 'package:lcs_new_age/location/location_type.dart';
import 'package:lcs_new_age/sitemode/sitemap.dart';

const locationFeatureCatalog = <SiteType, List<TileSpecial>>{
''' + '\n'.join(feature_rows) + '\n};\n\nconst locationLootCatalog = <SiteType, List<String>>{\n' + '\n'.join(loot_rows) + '\n};\n'
(ROOT / 'lib/modern/location_catalog.dart').write_text(output)
print(f'Generated {len(feature_rows)} feature profiles and {len(loot_rows)} loot profiles.')
