"""Record human face frames for vector dressings, without changing artwork.

Requires opencv-python-headless<5. Run after adding portrait sheets. Unrecognised
faces are omitted, so the renderer never guesses where a missing eye belongs.
"""
from pathlib import Path
import cv2

root = Path(__file__).resolve().parents[1]
cascade = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')
entries = []
missing = []
for path in sorted((root/'upstream/assets/modern/portraits_v2').glob('batch_*.png')):
    batch = int(path.stem.split('_')[1])
    if batch in (21,22):
        continue  # Animals, tanks and monsters do not have human facial landmarks.
    image=cv2.imread(str(path))
    h,w=image.shape[:2]
    for cell in range(16):
        idx=batch*16+cell if batch<16 else 250+(batch-16)*16+cell
        if batch==15 and cell>=10:
            continue
        tile=image[int(cell//4*h/4):int((cell//4+1)*h/4),int(cell%4*w/4):int((cell%4+1)*w/4)]
        faces=cascade.detectMultiScale(cv2.cvtColor(tile,cv2.COLOR_BGR2GRAY),1.08,4,minSize=(45,45))
        faces=[r for r in faces if r[2]>tile.shape[1]*.25 and r[1]<tile.shape[0]*.5]
        if len(faces):
            x,y,fw,fh=max(faces,key=lambda r:r[2]*r[3])
            entries.append(f'  {idx}: Rect.fromLTWH({x/tile.shape[1]:.4f}, {y/tile.shape[0]:.4f}, {fw/tile.shape[1]:.4f}, {fh/tile.shape[0]:.4f}),')
        else:
            missing.append(idx)
output=root/'upstream/lib/modern/portrait_face_frames.dart'
output.write_text("// Generated by scripts/portrait_face_frames.py; artwork is never modified.\nimport 'dart:ui';\n\nconst portraitFaceFrames = <int, Rect>{\n"+'\n'.join(entries)+'\n};\n')
print(f'{len(entries)} face frames recorded; omitted: {missing}')
